QString TextUtils::toTraditional(const QString &simplified)
{
    if (simplified.isEmpty())
        return simplified;

    QString text = simplified;
    // 规则表已按“长串在前、单字在后”排好序，顺序替换即可：
    // 先命中词组，再对剩余的单字逐字转换。查不到的字符两边同形，原样保留。
    for (int i = 0; i < kRuleCount; ++i) {
        const QString from = QString::fromUtf16(kRules[i].from);
        const QString to   = QString::fromUtf16(kRules[i].to);
        if (from != to)
            text.replace(from, to);
    }
    return text;
}
